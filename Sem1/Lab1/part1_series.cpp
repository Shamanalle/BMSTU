// Лабораторная работа №1, часть 1. Вариант 5.
// Вывести на печать пять первых слагаемых суммы  S = sum_{n=1}^{inf} 1/2^n
// и сумму этих слагаемых. Задача решена тремя видами цикла:
// с предусловием (while), с постусловием (do-while) и for.
#include <iostream>
#include <iomanip>
using namespace std;

const int N = 5; // Число слагаемых, которые нужно вывести

int main()
{
    cout << fixed << setprecision(5);

    // 1. Цикл с предусловием (while)
    cout << "1) while:" << endl;
    {
        double sum = 0;  // Сумма слагаемых
        double a = 0.5;  // Текущее слагаемое 1/2^n, при n = 1 равно 1/2
        int n = 1;       // Номер слагаемого
        while (n <= N)   // Условие проверяется до выполнения тела цикла
        {
            cout << "  a" << n << " = 1/2^" << n << " = " << a << endl;
            sum += a;    // Добавляем слагаемое к сумме
            a /= 2;      // Следующее слагаемое в 2 раза меньше: 1/2^(n+1) = (1/2^n) / 2
            n++;
        }
        cout << "  Sum = " << sum << endl << endl;
    }

    // 2. Цикл с постусловием (do-while)
    cout << "2) do-while:" << endl;
    {
        double sum = 0;
        double a = 0.5;
        int n = 1;
        do               // Тело цикла выполняется хотя бы один раз
        {
            cout << "  a" << n << " = 1/2^" << n << " = " << a << endl;
            sum += a;
            a /= 2;
            n++;
        } while (n <= N); // Условие проверяется после выполнения тела цикла
        cout << "  Sum = " << sum << endl << endl;
    }

    // 3. Цикл for
    cout << "3) for:" << endl;
    {
        double sum = 0;
        double a = 0.5;
        for (int n = 1; n <= N; n++, a /= 2) // Инициализация, условие и модификация в заголовке
        {
            cout << "  a" << n << " = 1/2^" << n << " = " << a << endl;
            sum += a;
        }
        cout << "  Sum = " << sum << endl << endl;
    }

    // Проверочное значение: сумма первых N слагаемых геометрической прогрессии
    // S_N = 1 - 1/2^N (при N = 5: 31/32 = 0.96875), полная сумма ряда равна 1
    cout << "Check: 1 - 1/2^5 = 31/32 = " << 31.0 / 32 << endl;
    cout << "Sum of infinite series = 1" << endl;
    return 0;
}
